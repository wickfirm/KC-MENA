// Regenerates src/lib/client-css.generated.ts from the client-delivered static site in reference/.
// The public site renders this CSS verbatim, so re-run after any change to reference/:
//   node scripts/sync-client-css.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ref = path.join(root, "reference");
const extract = (html) => [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");

// The hero-band background declaration, from the page CSS or the hero's inline style attribute.
const heroBackground = (html) =>
  html.match(/\.hero-band\s*\{[^}]*?background:\s*([^;]*);/)?.[1] ??
  html.match(/<section class="hero-band" style="background:([^"]*?);?"/)?.[1];

const pages = {};
const heroes = {};
const files = { home: path.join(ref, "index.html") };
for (const dir of readdirSync(ref).sort()) {
  if (statSync(path.join(ref, dir)).isDirectory() && dir !== "css" && dir !== "js") files[dir] = path.join(ref, dir, "index.html");
}
for (const [page, file] of Object.entries(files)) {
  const html = readFileSync(file, "utf8");
  pages[page] = extract(html);
  const hero = heroBackground(html);
  if (hero) heroes[page] = hero;
}
const site = readFileSync(path.join(ref, "css", "site.css"), "utf8");

writeFileSync(
  path.join(root, "src", "lib", "client-css.generated.ts"),
  "// GENERATED by scripts/sync-client-css.mjs from reference/ — do not edit by hand.\n" +
    `export const CLIENT_SITE_CSS = ${JSON.stringify(site)};\n\n` +
    `export const CLIENT_PAGE_CSS = ${JSON.stringify(pages, null, 1)} as const;\n\n` +
    `export const CLIENT_HERO_BACKGROUND: Record<string, string> = ${JSON.stringify(heroes, null, 1)};\n`,
);
console.log(`client-css.generated.ts: site.css + ${Object.keys(pages).length} pages, ${Object.keys(heroes).length} hero backgrounds`);
